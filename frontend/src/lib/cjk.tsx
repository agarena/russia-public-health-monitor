// 中文正文防断行：浏览器默认可在任意两个汉字间断行，会把「肺炎」「肺鼠疫」这类
// 领域词劈成两半。这里把本站领域词表命中的词用 U+2060（零宽词连接符）逐字粘住，
// 让它作为整体换行。
//
// 为什么不用 nowrap span：span 是不可拆的内联盒，长单元放不下时会整体跳到下一行，
// 把前一段撑出大面积留白（曾因一个 10 字引文 span 导致首行短了 155px）。U+2060
// 只禁止连接符位置断行，不引入任何 DOM 节点，排版副作用只剩术语自身宽度。
//
// 避头尾（标点不出现在行首/行尾，如「，」不落行首、「「」不落行尾）由全局 CSS
// line-break: strict 负责，见 index.css，不在此处理。数字区间（150–200）的连接符
// 同样在此粘住，避免从破折号处断开。
import type { ReactNode } from "react";

/** 本站领域词表：长词在前，避免短词先把长词切碎（如先粘「不明原因肺炎」再粘「肺炎」）。
 *  词长上限 6 字：过长的粘连单元放不下时会整体跳行，把前一行撑出大面积留白 */
const GLOSSARY = [
  // 事件与疾病
  "不明原因重症肺炎",
  "不明原因肺炎",
  "重症肺炎",
  "肺鼠疫",
  "肺炎",
  "鼠疫",
  "病原体",
  "病原学",
  "流行病学",
  // 处置与观察
  "防疫措施",
  "预防性隔离",
  "医学观察",
  "接触者",
  "核酸检测",
  "实验室",
  "隔离",
  // 信息与来源
  "公开信息",
  "官方口径",
  "官方",
  "媒体报道",
  "独立媒体",
  "热搜关键词",
  "核验状态",
  "无流行风险",
  "流行风险",
  // 机构
  "世界卫生组织",
  "世卫组织",
  "疾控",
];

/** 零宽词连接符：禁止在其位置断行，本身不占宽度 */
const WJ = "\u2060";

/** 把一段中文正文按领域词表粘合关键术语，防止从词中间断行 */
export function cjkProse(text: string): ReactNode {
  if (!text) return text;
  let out = text;
  // 数字区间（150–200）的连接符两侧不断行
  out = out.replace(/(\d)\s*([–—-])\s*(\d)/g, `$1${WJ}$2${WJ}$3`);
  // 术语逐字粘合：长词优先，已被粘合的内部不会再被短词命中
  for (const term of GLOSSARY) {
    if (term.length < 2) continue;
    out = out.split(term).join([...term].join(WJ));
  }
  return out;
}
